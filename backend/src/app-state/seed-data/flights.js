function createFlight(id, airline, code, departureTime, arrivalTime, durationMinutes, stops, price, tag) {
    return {
        id,
        airline,
        code,
        from: "NYC",
        to: "DXB",
        fromCity: "New York",
        toCity: "Dubai",
        departureTime,
        arrivalTime,
        duration: formatDuration(durationMinutes),
        durationMinutes,
        stops,
        stopLabel: getStopLabel(stops),
        price,
        tag,
        terminal: getTerminal(id),
        gate: getGate(id),
        aircraft: getAircraft(airline)
    };
}

function formatDuration(durationMinutes) {
    const hours = Math.floor(durationMinutes / 60);
    const minutes = durationMinutes % 60;
    return `${hours}h ${String(minutes).padStart(2, "0")}m`;
}

function getStopLabel(stops) {
    if (stops === 0) return "Non-stop";
    if (stops === 1) return "1 Stop";
    return "2+ Stops";
}

function getTerminal(id) {
    const terminals = ["Terminal 1", "Terminal 4", "Terminal 5", "Terminal 7", "Terminal 8"];
    return terminals[id % terminals.length];
}

function getGate(id) {
    const letters = ["A", "B", "C", "D", "E", "F", "G", "H"];
    const letter = letters[id % letters.length];
    const number = String((id % 27) + 3).padStart(2, "0");
    return `${letter}${number}`;
}

